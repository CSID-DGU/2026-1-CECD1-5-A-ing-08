CREATE TABLE public.meeting_pre_briefings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL,
    type VARCHAR(40) NOT NULL,
    schema_version INTEGER NOT NULL DEFAULT 1,
    payload JSONB NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_meeting_pre_briefings_meeting FOREIGN KEY (meeting_id) REFERENCES public.meetings (id) ON DELETE CASCADE,
    CONSTRAINT uq_meeting_pre_briefings_meeting_type UNIQUE (meeting_id, type)
);

CREATE TABLE public.meeting_post_coachings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL,
    schema_version INTEGER NOT NULL DEFAULT 1,
    payload JSONB NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_meeting_post_coachings_meeting FOREIGN KEY (meeting_id) REFERENCES public.meetings (id) ON DELETE CASCADE,
    CONSTRAINT uq_meeting_post_coachings_meeting UNIQUE (meeting_id)
);

ALTER TABLE public.meeting_pre_briefings ENABLE ROW LEVEL SECURITY;
